/**
 * Generating and installing the hook configuration.
 *
 * Two hard rules from the spec govern this file:
 *
 *  - The only paths Muster writes under `<config>` are its own hook scripts.
 *  - Settings edits require explicit user approval, so the generator produces a
 *    fragment and a diff-ready merged document; writing is a separate, opt-in call.
 *
 * The merge is conservative: existing entries are preserved and Muster's own
 * entries are replaced by identity, so re-running never accumulates duplicates
 * and never removes a hook the user configured themselves.
 */

import { mkdir, writeFile, readFile, rename, chmod } from 'node:fs/promises';
import * as path from 'node:path';
import type { ClaudePaths } from '../paths.js';
import { MUSTER_HOOK_EVENTS, type MusterHookEvent } from './events.js';
import {
  BASH_HOOK_FILENAME,
  POWERSHELL_HOOK_FILENAME,
  bashHookScript,
  powershellHookScript,
} from './scripts.js';

/** Marks an entry as Muster's, so regeneration can replace exactly its own. */
export const MUSTER_HOOK_MARKER = 'muster-hook';

export interface CommandHookHandler {
  readonly type: 'command';
  readonly command: string;
  readonly args?: readonly string[];
  readonly shell?: 'bash' | 'powershell';
  readonly async?: boolean;
  readonly timeout?: number;
  readonly statusMessage?: string;
}

export interface HookMatcherGroup {
  readonly matcher?: string;
  readonly hooks: readonly CommandHookHandler[];
}

export type HooksConfig = Partial<Record<string, HookMatcherGroup[]>>;

/**
 * Matchers per event.
 *
 * Notification is filtered to the two types the spec names plus the states
 * where a session is parked on a person. Matcher syntax: a plain list separated
 * by `|` is an exact-match list, not a regex.
 */
const EVENT_MATCHERS: Partial<Record<MusterHookEvent, string>> = {
  Notification: 'agent_needs_input|agent_completed|permission_prompt|elicitation_dialog',
};

export interface GenerateOptions {
  /** Emit PowerShell entries instead of bash. Defaults to the current platform. */
  readonly windows?: boolean | undefined;
}

/**
 * Builds the `hooks` fragment for settings.json.
 *
 * Every entry is `async: true`: these hooks only observe, and running them
 * inline would add a network round trip to each agent turn. Async delivery is
 * exactly the "hooks are the fast path, never the only path" contract — a
 * dropped delivery is corrected by the next reconciliation poll.
 */
export function generateHookConfig(paths: ClaudePaths, options: GenerateOptions = {}): HooksConfig {
  const windows = options.windows ?? process.platform === 'win32';
  const script = path.join(
    paths.hookScriptsDir(),
    windows ? POWERSHELL_HOOK_FILENAME : BASH_HOOK_FILENAME,
  );

  const config: HooksConfig = {};
  for (const event of MUSTER_HOOK_EVENTS) {
    const handler: CommandHookHandler = {
      type: 'command',
      command: script,
      // Exec form (`args` present) means no shell parses the path, so spaces in
      // a Windows profile directory cannot break the invocation.
      args: [event],
      ...(windows ? { shell: 'powershell' as const } : {}),
      async: true,
      timeout: 10,
      statusMessage: MUSTER_HOOK_MARKER,
    };

    const matcher = EVENT_MATCHERS[event];
    config[event] = [matcher === undefined ? { hooks: [handler] } : { matcher, hooks: [handler] }];
  }

  return config;
}

/** True when a handler was generated by Muster and may be replaced. */
function isMusterHandler(handler: unknown): boolean {
  if (typeof handler !== 'object' || handler === null) return false;
  const record = handler as Record<string, unknown>;
  if (record['statusMessage'] === MUSTER_HOOK_MARKER) return true;
  const command = record['command'];
  return (
    typeof command === 'string' &&
    (command.includes(BASH_HOOK_FILENAME) || command.includes(POWERSHELL_HOOK_FILENAME))
  );
}

/**
 * Merges the generated config into existing settings.
 *
 * Pure: returns a new document so the caller can diff it, show it, and only
 * then write. Groups are matched on `matcher` so a user's own entry for the
 * same event survives untouched.
 */
export function mergeHookConfig(
  settings: Record<string, unknown>,
  generated: HooksConfig,
): Record<string, unknown> {
  const existingHooks =
    typeof settings['hooks'] === 'object' && settings['hooks'] !== null
      ? ({ ...(settings['hooks'] as Record<string, unknown>) })
      : {};

  for (const [event, groups] of Object.entries(generated)) {
    if (groups === undefined) continue;

    const priorRaw = existingHooks[event];
    const prior = Array.isArray(priorRaw) ? (priorRaw as HookMatcherGroup[]) : [];

    // Drop Muster's previous handlers, keeping every other hook in place.
    const preserved: HookMatcherGroup[] = [];
    for (const group of prior) {
      if (typeof group !== 'object' || group === null) continue;
      const handlers = Array.isArray(group.hooks) ? group.hooks : [];
      const kept = handlers.filter((handler) => !isMusterHandler(handler));
      if (kept.length > 0) preserved.push({ ...group, hooks: kept });
    }

    // Fold ours into a group with the same matcher when one already exists, so
    // the file stays readable instead of growing parallel groups.
    const merged = [...preserved];
    for (const group of groups) {
      const index = merged.findIndex((candidate) => candidate.matcher === group.matcher);
      if (index === -1) {
        merged.push(group);
      } else {
        const target = merged[index];
        if (target !== undefined) {
          merged[index] = { ...target, hooks: [...target.hooks, ...group.hooks] };
        }
      }
    }

    existingHooks[event] = merged;
  }

  return { ...settings, hooks: existingHooks };
}

/**
 * Removes Muster's entries from settings, leaving everything else alone.
 * Backs the uninstall action.
 */
export function removeHookConfig(settings: Record<string, unknown>): Record<string, unknown> {
  const hooksRaw = settings['hooks'];
  if (typeof hooksRaw !== 'object' || hooksRaw === null) return settings;

  const hooks: Record<string, unknown> = {};
  for (const [event, groupsRaw] of Object.entries(hooksRaw as Record<string, unknown>)) {
    if (!Array.isArray(groupsRaw)) {
      hooks[event] = groupsRaw;
      continue;
    }
    const groups: HookMatcherGroup[] = [];
    for (const group of groupsRaw as HookMatcherGroup[]) {
      if (typeof group !== 'object' || group === null) continue;
      const kept = (Array.isArray(group.hooks) ? group.hooks : []).filter((h) => !isMusterHandler(h));
      if (kept.length > 0) groups.push({ ...group, hooks: kept });
    }
    if (groups.length > 0) hooks[event] = groups;
  }

  return { ...settings, hooks };
}

export interface HookInstallPlan {
  /** Scripts to write. Both dialects are always installed so a synced config works on either OS. */
  readonly scripts: readonly { path: string; contents: string; mode: number }[];
  readonly settingsFile: string;
  readonly currentSettings: Record<string, unknown>;
  readonly mergedSettings: Record<string, unknown>;
  /** JSON the user is asked to approve. */
  readonly diffPreview: string;
  /** True when settings already contain exactly this configuration. */
  readonly settingsUnchanged: boolean;
}

async function readSettings(file: string): Promise<Record<string, unknown>> {
  try {
    const parsed: unknown = JSON.parse(await readFile(file, 'utf8'));
    return typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {};
  } catch {
    // Missing or unreadable settings are treated as empty; the write path never
    // clobbers a file it could not parse (see installHooks).
    return {};
  }
}

/**
 * Prepares the install without touching disk.
 *
 * Both script dialects are written regardless of platform: users sync
 * `~/.claude` between machines, and a config referencing a missing script would
 * fail on the other OS.
 */
export async function planHookInstall(
  paths: ClaudePaths,
  options: GenerateOptions = {},
): Promise<HookInstallPlan> {
  const current = await readSettings(paths.settingsFile());
  const generated = generateHookConfig(paths, options);
  const merged = mergeHookConfig(current, generated);

  return {
    scripts: [
      {
        path: path.join(paths.hookScriptsDir(), BASH_HOOK_FILENAME),
        contents: bashHookScript(),
        mode: 0o755,
      },
      {
        path: path.join(paths.hookScriptsDir(), POWERSHELL_HOOK_FILENAME),
        contents: powershellHookScript(),
        mode: 0o644,
      },
    ],
    settingsFile: paths.settingsFile(),
    currentSettings: current,
    mergedSettings: merged,
    diffPreview: JSON.stringify({ hooks: merged['hooks'] }, null, 2),
    settingsUnchanged: JSON.stringify(current['hooks']) === JSON.stringify(merged['hooks']),
  };
}

export interface InstallResult {
  readonly scriptsWritten: readonly string[];
  readonly settingsWritten: boolean;
}

/**
 * Executes a plan. Call only after the user has approved `diffPreview`.
 *
 * Scripts always install (they are Muster's own files). Settings are written
 * only when `approveSettingsEdit` is true, and refuse to proceed if the file
 * exists but could not be parsed — overwriting an unreadable settings file
 * would destroy configuration this app has no business touching.
 */
export async function installHooks(
  plan: HookInstallPlan,
  options: { approveSettingsEdit: boolean },
): Promise<InstallResult> {
  const written: string[] = [];

  for (const script of plan.scripts) {
    await mkdir(path.dirname(script.path), { recursive: true });
    await writeFile(script.path, script.contents, 'utf8');
    // chmod is a no-op on Windows; harmless there and required on macOS.
    await chmod(script.path, script.mode).catch(() => undefined);
    written.push(script.path);
  }

  if (!options.approveSettingsEdit || plan.settingsUnchanged) {
    return { scriptsWritten: written, settingsWritten: false };
  }

  let existingText: string | undefined;
  try {
    existingText = await readFile(plan.settingsFile, 'utf8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
  }
  if (existingText !== undefined) {
    try {
      JSON.parse(existingText);
    } catch {
      throw new Error(
        `${plan.settingsFile} is not valid JSON; refusing to overwrite it. Fix or move the file, then retry.`,
      );
    }
  }

  await mkdir(path.dirname(plan.settingsFile), { recursive: true });
  const temp = `${plan.settingsFile}.muster.tmp`;
  await writeFile(temp, `${JSON.stringify(plan.mergedSettings, null, 2)}\n`, 'utf8');
  await rename(temp, plan.settingsFile);

  return { scriptsWritten: written, settingsWritten: true };
}
